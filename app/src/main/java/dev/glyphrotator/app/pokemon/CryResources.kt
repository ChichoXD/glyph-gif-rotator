/**
 * Cries de los 151 de primera generacion, en tres variantes de sonido.
 *
 * GENERADO por spraits/preparar_para_app.py. No editar a mano: si cambian los
 * audios, se vuelve a generar.
 *
 * Cada objeto expone CRY_RESOURCES: IntArray indexado por numero de Pokedex
 * menos 1 (CRY_RESOURCES[24] es Pikachu, el #025). Se listan las referencias
 * a R.raw en vez de resolverlas con `resources.getIdentifier(...)` porque R8
 * puede eliminar en release los recursos que solo se nombran como cadena:
 * funcionaria en debug y fallaria en la APK firmada.
 */
enum class CrySoundSet(@androidx.annotation.StringRes val labelRes: Int) {
    LEGACY(R.string.cry_set_legacy),
    HD(R.string.cry_set_hd),
    ANIME(R.string.cry_set_anime),
}

fun cryResourcesFor(set: CrySoundSet): IntArray = when (set) {
    CrySoundSet.LEGACY -> CRY_LEGACY
    CrySoundSet.HD -> CRY_HD
    CrySoundSet.ANIME -> CRY_ANIME
}

